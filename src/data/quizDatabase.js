/**
 * Retrieve or dynamically generate a 5-question multiple choice test quiz for any chapter
 */
export function getQuizForChapter(classNum, subjectId, chapterNum) {
  // Normalize parameters
  const cNum = String(classNum).replace(/class\s*/i, '').trim();
  const sKey = String(subjectId).toLowerCase().includes('sci') ? 'sci' :
               String(subjectId).toLowerCase().includes('sst') || String(subjectId).toLowerCase().includes('soc') ? 'sst' :
               String(subjectId).toLowerCase().includes('math') ? 'math' :
               String(subjectId).toLowerCase().includes('hin') ? 'hin' : 'sci';
  const chNum = parseInt(chapterNum, 10) || 1;

  // 1. Direct Lookup
  const directKey = `${cNum}_${sKey}_${chNum}`;
  if (CHAPTER_QUIZZES[directKey]) {
    return CHAPTER_QUIZZES[directKey];
  }

  // 2. Fallback to closest subject quiz in that class or flagship Class 8
  const fallbackKey = `${cNum}_${sKey}_1`;
  if (CHAPTER_QUIZZES[fallbackKey]) {
    return CHAPTER_QUIZZES[fallbackKey];
  }

  // 3. Flagship Standard Quiz
  return CHAPTER_QUIZZES['8_sst_16'];
}
