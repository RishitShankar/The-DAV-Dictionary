// Helper function to get chapters for any class and subject
export function getSubjectChapters(grade, subjectId, subjectName = '') {
  // Check explicit database first
  if (DAV_CHAPTERS[grade] && DAV_CHAPTERS[grade][subjectId]) {
    return DAV_CHAPTERS[grade][subjectId];
  }

  // Smart fallback chapter generator tailored for all DAV grades and subjects
  const defaultCount = grade === 8 ? 16 : grade >= 6 ? 14 : grade >= 3 ? 10 : 8;
  const chapters = [];
  
  for (let i = 1; i <= defaultCount; i++) {
    chapters.push({
      number: i,
      title: `Chapter ${i}: ${subjectName} Practice & Exercises Part ${i}`,
      tagline: `DAV Class ${grade} curriculum exercise solutions, short Q&A and workbook solutions`
    });
  }
  
  return chapters;
}
